import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { renderSignInPage } from "../plugin/chat/pages.mjs";

const DASHES = /[–—]/;

test("each sign-in state renders on its own, with no external resources and escaped text", () => {
  const pages = {
    form: renderSignInPage("form", { action: "/abc", minutesLeft: 9 }),
    invalid: renderSignInPage("form", { action: "/abc", minutesLeft: 1, invalid: ["sessionId"] }),
    saved: renderSignInPage("saved"),
    expired: renderSignInPage("expired"),
    error: renderSignInPage("error", { message: "<script>alert(1)</script>" }),
  };
  for (const [state, html] of Object.entries(pages)) {
    assert.match(html, /^<!doctype html>/, state);
    assert.doesNotMatch(html, /<script|<link|<img|src=|url\(/i, `${state} loads nothing`);
    assert.doesNotMatch(html, /(href|src|action)="https?:/, `${state} links nowhere`);
    assert.doesNotMatch(html, DASHES, `${state} has no em or en dash`);
    assert.match(html, /prefers-color-scheme: dark/);
  }
  assert.match(pages.form, /type="password"/);
  assert.match(pages.form, /closes in 9 minutes/);
  assert.match(pages.invalid, /aria-invalid="true"/);
  assert.match(pages.invalid, /closes in 1 minute\./);
  assert.match(pages.error, /&lt;script&gt;/);
  assert.match(pages.form, /Euler Stream/, "the page says where the cookies go");
});

// site/ is generated by build/site.mjs and committed; rebuild it after changing the manifest.
test("the landing page lists the real blocks, credits its software and links only where expected", () => {
  const html = readFileSync(new URL("../site/index.html", import.meta.url), "utf8");
  const manifest = JSON.parse(readFileSync(new URL("../plugin/manifest.json", import.meta.url), "utf8"));
  assert.doesNotMatch(html, /\{\{|\}\}/, "every placeholder is filled");
  assert.doesNotMatch(html, DASHES);
  for (const item of manifest.nodeTypes) assert.ok(html.includes(item.label.replace(/^TikTok: /, "").replace(/&/g, "&amp;")), item.type);
  for (const id of ["gifts", "audience", "battles", "install"]) assert.match(html, new RegExp(`id="${id}"`));
  for (const repo of ["https://github.com/zerodytrash/TikTok-Live-Connector", "https://github.com/isaackogan/TikTok-Webcast-Protobuf", "https://www.eulerstream.com", "https://tikfinity.zerody.one"]) assert.ok(html.includes(repo), repo);
  assert.match(html, /Unofficial integration/);
  const allowed = [/^https:\/\/github\.com\/(OSC-Flow-Studio|zerodytrash|isaackogan)\//, /^https:\/\/www\.eulerstream\.com/, /^https:\/\/tikfinity\.zerody\.one/];
  for (const [, href] of html.matchAll(/href="(https?:[^"]+)"/g)) assert.ok(allowed.some((rule) => rule.test(href)), href);
  assert.doesNotMatch(html, /<script[^>]+src="https?:/, "no script from a CDN");
  for (const [, tag] of html.matchAll(/(<img\b[^>]*>)/g)) assert.match(tag, /alt="[^"]{20,}"/, tag);
  assert.equal(new Set([...html.matchAll(/data-copy="([^"]+)"/g)].map((match) => match[1])).size, 1, "both buttons copy the same catalog URL");
});
