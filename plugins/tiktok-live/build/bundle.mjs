// Bundles tiktok-live-connector and its dependencies into plugin/vendor/, because the
// Studio runs a plugin with read access to its own folder only: a bare npm import fails
// there. Run it through `npm run bundle:tiktok-live` from the repository root.
//
// Writes:
//   plugin/vendor/tiktok-live-connector.mjs   the bundle
//   plugin/vendor/THIRD_PARTY_LICENSES.txt    the license text of every bundled package
//   plugin/vendor/NOTICE.md                   versions, licenses, links and the bundle hash
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const here = dirname(fileURLToPath(import.meta.url));
const vendorDir = join(here, "..", "plugin", "vendor");
const outfile = join(vendorDir, "tiktok-live-connector.mjs");

// Code the Studio's sandbox refuses, or that would mean the bundle reads files at run time.
const FORBIDDEN = [
  [/["']node:worker_threads["']|["']worker_threads["']/, "worker threads"],
  [/["']node:child_process["']|["']child_process["']/, "child processes"],
  [/\.node["']\)/, "a native addon"],
];

function packageRoot(input) {
  const parts = input.split("/");
  const at = parts.lastIndexOf("node_modules");
  if (at < 0) return null;
  const scoped = parts[at + 1].startsWith("@");
  return parts.slice(0, at + (scoped ? 3 : 2)).join("/");
}

function licenseText(root) {
  const file = readdirSync(root).find((name) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(name));
  return file ? readFileSync(join(root, file), "utf8").trim() : "";
}

function repositoryUrl(manifest) {
  const raw = typeof manifest.repository === "string" ? manifest.repository : manifest.repository?.url ?? "";
  const url = raw.replace(/^git\+/, "").replace(/\.git$/, "").replace(/^git:\/\//, "https://").replace(/^git@github\.com:/, "https://github.com/");
  if (/^[\w.-]+\/[\w.-]+$/.test(url)) return `https://github.com/${url}`;
  if (/^github:/.test(url)) return `https://github.com/${url.slice(7)}`;
  return url.replace(/^ssh:\/\/git@/, "https://");
}

mkdirSync(vendorDir, { recursive: true });
const result = await build({
  entryPoints: [join(here, "entry.mjs")],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  outfile,
  legalComments: "none",
  metafile: true,
  logLevel: "warning",
  // ws loads these optional native helpers when they exist; the sandbox has neither.
  external: ["bufferutil", "utf-8-validate"],
  // CommonJS dependencies (axios' helpers, debug) call require() for Node built-ins.
  banner: {
    js: [
      "// Generated by plugins/tiktok-live/build/bundle.mjs. Do not edit; see NOTICE.md.",
      'import { createRequire as __ofsCreateRequire } from "node:module";',
      "const require = __ofsCreateRequire(import.meta.url);",
    ].join("\n"),
  },
});

const code = readFileSync(outfile, "utf8");
const problems = FORBIDDEN.filter(([pattern]) => pattern.test(code)).map(([, what]) => what);
if (problems.length > 0) {
  console.error(`The bundle uses ${problems.join(", ")}, which the Studio's plugin sandbox refuses.`);
  process.exit(1);
}

const roots = [...new Set(Object.keys(result.metafile.inputs).map(packageRoot).filter(Boolean))];
const packages = roots
  .map((root) => {
    const absolute = join(here, ...root.split("/"));
    const manifest = JSON.parse(readFileSync(join(absolute, "package.json"), "utf8"));
    return {
      name: manifest.name,
      version: manifest.version,
      license: manifest.license ?? "see license text",
      repository: repositoryUrl(manifest),
      text: licenseText(absolute),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const missing = packages.filter((item) => !item.text);
for (const item of missing) console.warn(`${item.name} ${item.version} ships no license file; NOTICE.md names its license only.`);

const sha256 = createHash("sha256").update(readFileSync(outfile)).digest("hex");
const connector = packages.find((item) => item.name === "tiktok-live-connector");
if (!connector) throw new Error("tiktok-live-connector is not part of the bundle");

writeFileSync(join(vendorDir, "THIRD_PARTY_LICENSES.txt"), packages
  .map((item) => `${"=".repeat(78)}\n${item.name} ${item.version} (${item.license})\n${item.repository}\n${"=".repeat(78)}\n\n${item.text || `License: ${item.license}. The package ships no license file.`}\n`)
  .join("\n"));

writeFileSync(join(vendorDir, "NOTICE.md"), `# Third-party software in this folder

\`tiktok-live-connector.mjs\` is generated by \`plugins/tiktok-live/build/bundle.mjs\` in
https://github.com/OSC-Flow-Studio/official-community-plugins. It bundles
tiktok-live-connector ${connector.version} and the packages it depends on, unmodified.
The full license text of each one is in \`THIRD_PARTY_LICENSES.txt\`.

tiktok-live-connector and tiktok-live-proto are licensed under AGPL-3.0 with additional
permissions (sections 18 to 21 of their license): they may be built into client
applications, overlays and bots, and may not power a hosted relay or SaaS unless its
server-side source is published under AGPL-3.0. This plugin is a client that runs on your
own computer, and its complete source is public in the repository above.

| Package | Version | License | Source |
| --- | --- | --- | --- |
${packages.map((item) => `| ${item.name} | ${item.version} | ${item.license} | ${item.repository} |`).join("\n")}

Bundle SHA-256: \`${sha256}\`
`);

console.log(`${relative(join(here, ".."), outfile).split(sep).join("/")}: ${(code.length / 1024).toFixed(0)} KB, ${packages.length} packages, sha256 ${sha256}`);
if (!existsSync(join(vendorDir, "NOTICE.md"))) process.exit(1);
